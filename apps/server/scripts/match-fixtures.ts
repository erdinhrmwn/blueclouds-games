// Writes contracts/fixtures/bust-31-matches.json: whole bot games, shuffled and logged the way the room does it
// (fairness events included), for the backoffice's replay tests. Run it again when the move log changes:
//   bun apps/server/scripts/match-fixtures.ts

import type { MatchSeeds } from 'contracts/fairness/fairness'
import { must } from 'contracts/must'
import { toMatchId, toPlayerId } from '../src/core/domain/ids'
import type { LogEntry } from '../src/core/domain/match'
import { fairRng, matchSeeds, newCommitment, seedsForRound } from '../src/core/rules/fair-rng'
import { stamp } from '../src/core/rules/match'
import { closedRounds } from '../src/core/rules/rounds'
import { chooseBotCard } from '../src/games/bust-31/bots'
import type { Game, MatchState } from '../src/games/bust-31/domain'
import { logEvents } from '../src/games/bust-31/match'
import { addPlayer, createGame, playCard, startGame } from '../src/games/bust-31/rules'

const GAMES = 3
const OUT = new URL('../../../contracts/fixtures/bust-31-matches.json', import.meta.url)

/** A full 4-player bot game, shuffled and logged the way the room does it (fairness events included). */
function playedGame() {
  let game = createGame()
  for (let i = 0; i < 4; i++) {
    game = addPlayer(game, toPlayerId(`bot-${i}`), `Bot ${i}`, true)
  }

  let match: MatchState = {
    id: toMatchId('m'),
    startedAt: new Date(0).toISOString(),
    out: [],
    seq: 0,
  }
  let seeds: MatchSeeds = { ...matchSeeds(newCommitment()), matchId: 'm' }
  let pending: LogEntry[] = []
  const rng = fairRng(
    (round) => {
      const result = seedsForRound(seeds, round)
      seeds = result.seeds
      if (result.started) {
        const { roundId, serverSeedHash } = must(seeds.current, 'current seed')
        pending.push({ type: 'fairness', data: { round, roundId, serverSeedHash } })
      }

      return seeds
    },
    (record) => {
      pending.push({ type: 'shuffle', data: record })
      seeds = { ...seeds, last: record }
    },
  )
  const events: { seq: number; t: number; type: string }[] = []
  // As the room does: a closed round reveals its seed after its moves.
  const revealsOf = (moves: LogEntry[], finished: boolean) =>
    closedRounds(moves, seeds.current?.round ?? null, finished).map((round) => {
      const seed = must(
        [seeds.previous, seeds.current].find((held) => held?.round === round),
        'seed of the round',
      )
      return { type: 'reveal', data: { round, serverSeed: seed.serverSeed } }
    })
  const step = (next: Game) => {
    const moves = logEvents(game, next, true)
    const entries = [...pending, ...moves, ...revealsOf(moves, next.phase === 'finished')]
    pending = []
    const stamped = stamp(match, entries, events.length * 1000)
    match = stamped.match
    events.push(...stamped.events)
    game = next
  }

  const host = toPlayerId('bot-0')
  game = { ...game, hostId: host }
  step(startGame(game, host, rng))
  while (game.phase === 'playing') {
    const player = must(game.players[game.turn], 'player on turn')
    const card = must(chooseBotCard(player.hand, game.total), 'bot card')
    step(playCard(game, player.id, card.id, rng))
  }

  const seats = game.players.map((player) => ({ seat: player.seat, name: player.name }))
  const winner = game.players.find((player) => player.id === game.winnerId)?.name ?? null
  const lives = game.players.map((player) => Math.max(0, player.lives))
  return { log: { logVersion: 1, events }, seats, winner, lives }
}

const matches = Array.from({ length: GAMES }, playedGame)
const about =
  'Bust 31 bot games as the room logs them. Generated by apps/server/scripts/match-fixtures.ts.'
// One event per line: the file stays readable in a diff without growing to a line per card.
const lines = matches.map(({ log, ...rest }) => {
  const events = log.events.map((event) => `      ${JSON.stringify(event)}`).join(',\n')
  const head = JSON.stringify(rest).slice(1, -1)
  return `  {${head},"log":{"logVersion":${log.logVersion},"events":[\n${events}\n    ]}}`
})
await Bun.write(
  OUT,
  `{"about":${JSON.stringify(about)},"matchId":"m","matches":[\n${lines.join(',\n')}\n]}\n`,
)
console.log(`Wrote ${matches.length} matches to ${OUT.pathname}`)
